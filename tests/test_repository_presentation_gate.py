"""Focused tests for the repository presentation and attribution guard."""

import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts' / 'ci'))
import repository_presentation_gate as gate  # noqa: E402


class PresentationGateTests(unittest.TestCase):
    def test_functional_language_is_not_blocked(self):
        self.assertEqual(gate.matches('Automated CI checks and human review.'), [])
        self.assertEqual(gate.matches('financial_aid and school isolation'), [])

    def test_banned_labels_and_case(self):
        for value in ('Created with CoPiLoT.', 'AI-built product',
                      'Generated by ChatGPT', 'autonomous engineer',
                      '100% human-written', 'entirely human-authored'):
            with self.subTest(value=value):
                self.assertTrue(gate.matches(value))

    def event(self, event_name, key, item):
        with tempfile.TemporaryDirectory() as tmp:
            event = Path(tmp) / 'event.json'
            event.write_text(json.dumps({key: item}), encoding='utf-8')
            env = {'GITHUB_EVENT_NAME': event_name, 'GITHUB_EVENT_PATH': str(event)}
            return (gate.pr_violations(env) + gate.issue_violations(env)
                    + gate.release_violations(env))

    def test_pr_title_and_body(self):
        errs = self.event('pull_request', 'pull_request', {
            'number': 42, 'title': 'AI-built', 'body': 'Generated by Codex',
        })
        self.assertGreaterEqual(len(errs), 2)
        self.assertEqual(gate.pr_violations({'GITHUB_EVENT_NAME': 'push'}), [])
        self.assertTrue(self.event('pull_request', 'pull_request', {
            'number': 42, 'title': 'Neutral', 'body': 0,
        }))

    def test_missing_event_payload_fails_closed(self):
        for fn, event_name in ((gate.pr_violations, 'pull_request'),
                               (gate.issue_violations, 'issues'),
                               (gate.release_violations, 'release')):
            self.assertTrue(fn({'GITHUB_EVENT_NAME': event_name}))

    def test_first_party_issue_and_external_report(self):
        item = {'number': 42, 'title': 'AI-built', 'body': None}
        self.assertTrue(self.event('issues', 'issue', dict(item, author_association='OWNER')))
        self.assertEqual(self.event('issues', 'issue', dict(item, author_association='NONE')), [])
        self.assertTrue(self.event('issues', 'issue', item))

    def test_repository_metadata(self):
        clean = {'name': 'Jirehfinancialaid', 'description': 'Financial aid',
                 'homepage': None, 'topics': ['schools']}
        self.assertEqual(gate.metadata_violations(clean), [])
        self.assertTrue(gate.metadata_violations(dict(clean, topics=['ai'])))
        self.assertTrue(gate.metadata_violations(dict(clean, description='Made with Codex')))
        self.assertTrue(gate.metadata_violations(dict(clean, homepage='https://example.invalid/chatgpt')))
        self.assertTrue(gate.metadata_violations(dict(clean, topics=None)))

    def test_release_requires_review_of_exact_uploaded_asset(self):
        digest = 'sha256:' + 'a' * 64
        release = {'id': 42, 'name': 'Release', 'body': '', 'tag_name': 'v1',
                   'assets': [{'id': 9, 'name': 'guide.pdf', 'digest': digest}]}
        self.assertTrue(self.event('release', 'release', release))
        with patch.dict(gate.REVIEWED_RELEASE_ASSETS, {(42, 9, digest): ('sample reason', 'sample decision')}):
            self.assertEqual(self.event('release', 'release', release), [])
            changed = dict(release, assets=[{'id': 9, 'name': 'guide.pdf', 'digest': 'sha256:' + 'b' * 64}])
            self.assertTrue(self.event('release', 'release', changed))
            missing = dict(release, assets=[{'id': 9, 'name': 'guide.pdf'}])
            self.assertTrue(self.event('release', 'release', missing))
        self.assertTrue(self.event('release', 'release', dict(release, body='AI-built')))

    def init_repo(self, root):
        subprocess.run(['git', 'init', '-q', str(root)], check=True)

    def stage(self, root):
        subprocess.run(['git', '-C', str(root), 'add', '.'], check=True)

    def test_tracked_files_and_control_exceptions(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.init_repo(root)
            (root / 'docs').mkdir()
            (root / 'README.md').write_text('Verified by ChatGPT', encoding='utf-8')
            (root / 'docs' / 'REPOSITORY_PRESENTATION_AND_ATTRIBUTION_POLICY.md').write_text(
                'AI disclosure exceptions', encoding='utf-8')
            self.stage(root)
            violations, count = gate.tracked_violations(root)
            self.assertEqual(count, 0)
            self.assertEqual(len(violations), 1)
            self.assertIn('README.md:1:', violations[0])

    def test_unknown_extensions_and_staged_content_are_inspected(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.init_repo(root)
            (root / 'CODEOWNERS').write_text('Generated by Codex', encoding='utf-8')
            (root / 'notice.unknown').write_text('Created with ChatGPT', encoding='utf-16')
            (root / 'vendor').mkdir()
            (root / 'vendor' / 'NOTICE').write_text('Codex', encoding='utf-8')
            (root / 'package-lock.json').write_text('{"name": "openai"}', encoding='utf-8')
            (root / 'ai-notice').write_text('neutral', encoding='utf-8')
            self.stage(root)
            (root / 'CODEOWNERS').write_text('neutral working copy', encoding='utf-8')
            violations, count = gate.tracked_violations(root)
            self.assertEqual(count, 0)
            self.assertEqual(len(violations), 5)
            for path in ('CODEOWNERS:1', 'notice.unknown:1', 'vendor/NOTICE:1',
                         'package-lock.json:1', 'ai-notice: filename'):
                self.assertTrue(any(path in finding for finding in violations))

    def test_exact_reference_exception_does_not_hide_new_text(self):
        text = 'Required dependency attribution: OpenAI'
        key = ('NOTICE', 1, 'openai', hashlib.sha256(text.encode()).hexdigest())
        with patch.dict(gate.REVIEWED_REFERENCES, {key: ('required attribution', 'sample owner decision')}):
            self.assertEqual(gate._reference_violations('NOTICE', text), [])
            self.assertTrue(gate._reference_violations('NOTICE', text + ' changed'))
            self.assertTrue(gate._reference_violations('OTHER', text))
            self.assertTrue(gate._reference_violations('NOTICE', '\n' + text))
        self.assertTrue(gate._reference_violations('NOTICE', text))

    def test_assets_require_exact_object_review_even_if_text(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.init_repo(root)
            (root / 'guide.svg').write_text('<svg/>', encoding='utf-8')
            (root / 'opaque').write_bytes(b'\x00\xff')
            self.stage(root)
            violations, count = gate.tracked_violations(root)
            self.assertEqual((len(violations), count), (2, 2))
            oid = subprocess.check_output(['git', '-C', str(root), 'rev-parse', ':guide.svg'], text=True).strip()
            with patch.dict(gate.REVIEWED_ASSETS, {('guide.svg', oid): ('sample review', 'sample decision')}):
                violations, count = gate.tracked_violations(root)
                self.assertEqual((len(violations), count), (1, 2))
                (root / 'guide.svg').write_text('<svg>updated</svg>', encoding='utf-8')
                self.stage(root)
                self.assertEqual(len(gate.tracked_violations(root)[0]), 2)

    def test_symlink_requires_review_without_following_target(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.init_repo(root)
            (root / 'link').symlink_to('nonexistent-target')
            self.stage(root)
            violations, count = gate.tracked_violations(root)
            self.assertEqual((len(violations), count), (1, 1))
            self.assertIn('link object requires recorded review', violations[0])


if __name__ == '__main__':
    unittest.main()
