"""Focused tests for the repository presentation and attribution guard."""

from pathlib import Path
import json
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts' / 'ci'))
import repository_presentation_gate as gate  # noqa: E402


class PresentationGateTests(unittest.TestCase):
    def test_functional_language_is_not_blocked(self):
        self.assertEqual(gate.matches('Automated CI checks and human review.'), [])
        self.assertEqual(gate.matches('financial_aid and school isolation'), [])

    def test_banned_labels_and_case(self):
        self.assertTrue(gate.matches('Created with CoPiLoT.'))
        self.assertTrue(gate.matches('AI-built product'))
        self.assertTrue(gate.matches('Generated by ChatGPT'))

    def test_pr_title_and_body(self):
        with tempfile.TemporaryDirectory() as tmp:
            event = Path(tmp) / 'event.json'
            event.write_text(json.dumps({'pull_request': {
                'title': 'docs: neutral controls', 'body': 'AI-generated by Codex',
            }}), encoding='utf-8')
            errs = gate.pr_violations({'GITHUB_EVENT_NAME': 'pull_request',
                                       'GITHUB_EVENT_PATH': str(event)})
            self.assertGreaterEqual(len(errs), 2)
            self.assertEqual(gate.pr_violations({'GITHUB_EVENT_NAME': 'push'}), [])

    def test_missing_pr_payload_fails_closed(self):
        self.assertTrue(gate.pr_violations({'GITHUB_EVENT_NAME': 'pull_request'}))

    def test_tracked_files_and_control_exceptions(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'docs').mkdir()
            (root / 'README.md').write_text('Verified by ChatGPT', encoding='utf-8')
            (root / 'docs' / 'REPOSITORY_PRESENTATION_AND_ATTRIBUTION_POLICY.md').write_text(
                'AI disclosure exceptions', encoding='utf-8')
            import subprocess
            subprocess.run(['git', 'init', '-q', str(root)], check=True)
            subprocess.run(['git', '-C', str(root), 'add', '.'], check=True)
            violations, count = gate.tracked_violations(root)
            self.assertEqual(count, 0)
            self.assertEqual(len(violations), 1)
            self.assertIn('README.md:1:', violations[0])


if __name__ == '__main__':
    unittest.main()
